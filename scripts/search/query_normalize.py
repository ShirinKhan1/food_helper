@lru_cache(maxsize=1)
def _morph_analyzer():
    from pymorphy3 import MorphAnalyzer

    return MorphAnalyzer()


def _collapse_spaces(text: str) -> str:
    return " ".join(text.split())


def normalize_query_for_search(text: str) -> str:
    """
    NFC, lower case, токены, леммы pymorphy3, удаление стоп-слов.
    Если после фильтрации ничего не осталось — лёгкая очистка исходной строки.
    """
    raw = text.strip()
    if not raw:
        return ""

    nfc = unicodedata.normalize("NFC", raw)
    lowered = nfc.lower()
    morph = _morph_analyzer()

    lemmas: list[str] = []
    for m in _TOKEN_RE.finditer(lowered):
        token = m.group(0)
        if len(token) < 2:
            continue
        lemma = morph.parse(token)[0].normal_form
        if len(lemma) < 2:
            continue
        if lemma in RUSSIAN_STOPWORDS:
            continue
        lemmas.append(lemma)

    if lemmas:
        return " ".join(lemmas)

    return _collapse_spaces(nfc)
